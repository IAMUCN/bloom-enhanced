// Writes src/lightFixes.css: for each notch/dock/shelf stylesheet, a light-mode
// copy of every rule that paints with translucent white (dark-theme chips,
// borders, dim text), turned into translucent dark so it stays visible on a
// light surface. Rules that already have a hand-written `.light-mode` twin
// are skipped. Run: bun scripts/genLightFixes.ts
import { readFileSync, writeFileSync } from "fs";

const files = [
	"App.css", "Dock.css", "components/ClipboardPanel.css", "components/QuickPanel.css",
	"components/CommandCenter.css", "notchTools/tools.css", "Orbit.css", "ClipShelf.css", "Overlay.css"
];
const WHITE = /rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*([0-9.]+)\s*\)/g;
const out: string[] = ["/* Generated by scripts/genLightFixes.ts. Do not edit by hand. */"];

for (const f of files) {
	const css = readFileSync(`src/${f}`, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
	const handwritten = new Set([...css.matchAll(/\.light-mode\s+([^{,]+)[,{]/g)].map((m) => m[1].trim()));
	const rules: string[] = [];
	// Top-level rules only (skips @media / @keyframes blocks).
	let depth = 0, start = 0, sel = "";
	for (let i = 0; i < css.length; i++) {
		const c = css[i];
		if (c === "{") { if (depth === 0) sel = css.slice(start, i).trim(); depth++; }
		else if (c === "}") {
			depth--;
			if (depth === 0) {
				const body = css.slice(css.indexOf("{", start) + 1, i);
				start = i + 1;
				if (sel.startsWith("@") || /^(:root|html|body|\.light-mode|\.dark-mode)/.test(sel)) continue;
				const selectors = sel.split(",").map((s) => s.trim()).filter(Boolean);
				if (selectors.some((s) => handwritten.has(s))) continue;
				const hasBg = /(^|;|\s)background(-color)?\s*:/.test(body);
				const decls: string[] = [];
				for (const d of body.split(";")) {
					const m = d.match(/^\s*([a-z-]+)\s*:\s*([\s\S]+)$/);
					if (!m || !WHITE.test(m[2])) { WHITE.lastIndex = 0; continue; }
					WHITE.lastIndex = 0;
					const prop = m[1];
					const ok = /^(background|background-color|border|border-color|border-top|border-bottom|border-left|border-right|outline)$/.test(prop) ||
						(/^(color|fill|stroke)$/.test(prop) && !hasBg);
					if (!ok || m[2].includes("gradient") || m[2].includes("var(")) continue;
					decls.push(`${prop}: ${m[2].replace(WHITE, (_, a) => `rgba(0, 0, 0, ${Math.min(1, Number(a) * (/^(color|fill|stroke)$/.test(prop) ? 1 : 0.8)).toFixed(2)})`).trim()}`);
				}
				if (decls.length) rules.push(`${selectors.map((s) => `.light-mode ${s}`).join(",\n")} {\n\t${decls.join(";\n\t")};\n}`);
			}
		}
		else if (depth === 0 && c === "}") start = i + 1;
		if (depth === 0 && (c === "}" || c === ";")) start = i + 1;
	}
	if (rules.length) out.push(`/* ${f} */`, ...rules);
}
writeFileSync("src/lightFixes.css", out.join("\n") + "\n");
console.log("rules:", out.length - 1);
